"""Bringup settings from a file, so a pool day is a file and not a long command.

`bringup.launch.py` has ~100 arguments. Typing ten of them correctly, at the
pool, under time pressure, is how a run gets lost -- and `ros2 launch` makes it
worse, because a mistyped `name:=value` is ignored without a word.

So the same arguments can live in a YAML file on the vehicle:

    # ~/.mongla/bringup.yaml
    vision: true
    flow: true
    pool_depth_m: 1.2
    fwd_model: gate_sharks

and `ros2 launch mongla_manager bringup.launch.py` reads it.

The same file also holds NODE PARAMETERS -- the ~200 knobs that are not launch
arguments (vision gains, lock ladder, filter noise) -- under one key, `nodes:`,
keyed by node name:

    nodes:
      mongla_manager:
        vision.kp_yaw: 80.0           # or nested: vision: {kp_yaw: 80.0}

One file, one place to look on the deck. Bringup hands `nodes:` to every node
it starts, and each node REFUSES a key it does not declare, because ROS
ignores one without a word (`mongla_localization/params_file.py`). A key the
launch file already sets from an argument is refused too: it would lose to
the argument, so it belongs at the top level under the argument's name.

Which launch-argument value wins, highest first:

    1. `name:=value` typed on the command line      (always wins)
    2. the file                                      (the deck's settings)
    3. the default written in bringup.launch.py      (the repository's)

The file is `$MONGLA_BRINGUP` if set, else `~/.mongla/bringup.yaml`; if
neither exists nothing changes. `MONGLA_BRINGUP=none` ignores the file.

Unlike the command line, the file is STRICT: a key that is not a bringup
argument stops the launch with the closest real name, and a value outside an
argument's choices stops it too. A typo here fails at launch, on the bench, and
not silently at depth.

The other launch files read the same file, each from its own section under
`launch:`, keyed by the file's name without `.launch.py`:

    launch:
      vision_dual:                    # ros2 launch mongla_vision vision_dual.launch.py
        fwd_model: gate_sharks
      video:
        fwd_video: /footage/gate.mp4

A section applies only to the launch file the operator TYPED. When bringup
includes `vision_pi.launch.py`, the `vision_pi:` section is not read: bringup
passes those arguments itself, from the top level of this file. The same
strictness holds: a section name that is not a launch file, or a key the
launch file does not declare, stops the launch. `nodes:` applies to whichever
launch file was typed.

It lives in `mongla_localization` because every package that has a launch
file already depends on it (the same reason `params_file.py` is here).

An example with every argument and its default:
`src/mongla_manager/config/bringup.example.yaml` (generated by
`tools/ci/gen_reference.py`).
"""
from __future__ import annotations

import difflib
import os
import sys
from pathlib import Path

ENV = 'MONGLA_BRINGUP'
NODES_KEY = 'nodes'
LAUNCH_KEY = 'launch'
# Launch files other than bringup that read a section of the file. A test
# compares this with the launch files in the repository.
SECTIONS = ('mission_web', 'video', 'vision', 'vision_dual', 'vision_pi')
DEFAULT_PATH = Path.home() / '.mongla' / 'bringup.yaml'


def config_path() -> Path | None:
    """The file bringup will read, or None if there is none to read."""
    env = os.environ.get(ENV, '').strip()
    if env.lower() in ('none', 'off', '0'):
        return None
    p = Path(env).expanduser() if env else DEFAULT_PATH
    if env and not p.exists():
        # Pointing at a file that is not there is a mistake worth stopping for:
        # the operator believes settings are applied that are not.
        raise RuntimeError(f'{ENV}={env}: no such file')
    return p if p.exists() else None


def _as_launch_string(value) -> str:
    """YAML value -> the string `name:=value` would have produced."""
    if isinstance(value, bool):
        return 'true' if value else 'false'
    if value is None:
        return ''
    if isinstance(value, (list, tuple)):
        return ','.join(str(v) for v in value)
    return str(value)


def _refuse_unknown(path: Path, keys, declared, what: str) -> None:
    unknown = sorted(set(keys) - set(declared))
    if not unknown:
        return
    hints = []
    for k in unknown:
        close = difflib.get_close_matches(str(k), declared, n=1)
        hints.append(f'{k!r}' + (f' (did you mean {close[0]!r}?)' if close else ''))
    raise RuntimeError(f'{path}: not {what}: {", ".join(hints)}')


def read(path: Path, declared: set[str], section: str | None = None) -> dict[str, str]:
    """{argument: value} from the file; refuses a key the launch file does not declare.

    `section=None` reads the top level (bringup); a name reads `launch: <name>:`.
    """
    import yaml
    body = yaml.safe_load(path.read_text()) or {}
    if not isinstance(body, dict):
        raise RuntimeError(f'{path}: expected `name: value` lines, got {type(body).__name__}')
    sections = body.get(LAUNCH_KEY) or {}
    if not isinstance(sections, dict):
        raise RuntimeError(f'{path}: `{LAUNCH_KEY}:` must map launch file names to arguments')
    _refuse_unknown(path, sections, SECTIONS, f'a launch file with a `{LAUNCH_KEY}:` section')
    if section is None:
        _refuse_unknown(path, set(body) - {NODES_KEY, LAUNCH_KEY}, declared,
                        'a bringup argument')
        values = {k: v for k, v in body.items() if k not in (NODES_KEY, LAUNCH_KEY)}
    else:
        values = sections.get(section) or {}
        if not isinstance(values, dict):
            raise RuntimeError(f'{path}: {LAUNCH_KEY}: {section}: expected `name: value` lines')
        _refuse_unknown(path, values, declared, f'a {section}.launch.py argument')
    return {str(k): _as_launch_string(v) for k, v in values.items()}


def apply(args: list, section: str | None = None) -> tuple[list, dict[str, str], Path | None]:
    """Re-default `DeclareLaunchArgument`s from the file (its top level, or a section).

    Returns (new argument list, the values the file set, the file's path).
    Arguments the file does not name are returned untouched.
    """
    from launch.actions import DeclareLaunchArgument
    path = config_path()
    if path is None:
        return args, {}, None
    declared = {a.name for a in args if isinstance(a, DeclareLaunchArgument)}
    values = read(path, declared, section)
    out = []
    for a in args:
        if not (isinstance(a, DeclareLaunchArgument) and a.name in values):
            out.append(a)
            continue
        desc = a.description.split(' Valid choices are:')[0]
        # Re-declaring with the file's value as the default puts it BELOW the
        # command line: launch only uses a default when `name:=` is not given.
        # The constructor checks the value against `choices` and raises.
        try:
            out.append(DeclareLaunchArgument(a.name, default_value=values[a.name],
                                             description=desc, choices=a.choices))
        except RuntimeError:
            raise RuntimeError(f'{path}: {a.name}: {values[a.name]!r} is not one '
                               f'of {a.choices}') from None
    return out, values, path



def read_nodes(path: Path) -> dict[str, dict]:
    """The file's `nodes:` section: {node_name: {param: value}}; refuses a bad shape.

    A wildcard name (`/**`, `mongla_*`) is refused: it reaches every node, so no
    node could tell its own typo from another node's real parameter.
    """
    import yaml
    body = yaml.safe_load(path.read_text()) or {}
    nodes = body.get(NODES_KEY) if isinstance(body, dict) else None
    if nodes is None:
        return {}
    if not isinstance(nodes, dict):
        raise RuntimeError(f'{path}: `{NODES_KEY}:` must map node names to parameters')
    out = {}
    for name, params in nodes.items():
        name = str(name).strip('/')
        if '*' in name:
            raise RuntimeError(f'{path}: nodes: {name!r}: name each node; a '
                               f'wildcard cannot be checked for typos')
        if not isinstance(params, dict) or 'ros__parameters' in params:
            raise RuntimeError(f'{path}: nodes: {name!r}: expected `param: value` '
                               f'lines (no `ros__parameters:` level -- bringup adds it)')
        out[name] = params
    return out


def node_actions() -> list:
    """Launch actions that hand `nodes:` to every node bringup starts, or []."""
    path = config_path()
    nodes = read_nodes(path) if path is not None else {}
    if not nodes:
        return []
    import tempfile
    import yaml
    from launch.actions import LogInfo, SetEnvironmentVariable
    from launch_ros.actions import SetParametersFromFile
    from mongla_localization.params_file import APPLIED_ENV
    # The ROS form of the section. One file per user, rewritten by every
    # launch, so launches do not pile up copies in /tmp (a RAM disk here).
    ros_file = os.path.join(tempfile.gettempdir(), f'mongla-nodes-{os.getuid()}.yaml')
    with open(ros_file, 'w') as f:
        yaml.safe_dump({n: {'ros__parameters': p} for n, p in nodes.items()}, f)
    return [
        LogInfo(msg=f'[bringup] node parameters from {path}: {", ".join(sorted(nodes))}'),
        SetEnvironmentVariable(APPLIED_ENV, ros_file),
        SetParametersFromFile(ros_file),
    ]


def typed(launch_file: str) -> bool:
    """True when `launch_file` is the one on the `ros2 launch` command line.

    False when another launch file included it: that one passes its arguments
    explicitly, and a section here must not change the ones it leaves out.
    """
    name = os.path.basename(launch_file)
    return any(os.path.basename(a) == name for a in sys.argv[1:])


def for_launch_file(args: list, launch_file: str) -> tuple[list, list]:
    """(arguments, extra actions) for a launch file other than bringup.

    The arguments are re-defaulted from the file's `launch: <name>:` section and
    the actions carry `nodes:`, both only when this file was typed; otherwise
    both come back unchanged.
    """
    if not typed(launch_file):
        return args, []
    from launch.actions import LogInfo
    section = os.path.basename(launch_file).removesuffix('.launch.py')
    args, values, path = apply(args, section)
    note = ([LogInfo(msg=f'[{section}] settings from {path}: ' + ', '.join(
        f'{k}={v}' for k, v in sorted(values.items())))] if values else [])
    return args, note + node_actions()
