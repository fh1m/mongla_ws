"""Bringup settings from a file, so a pool day is a file and not a long command.

`bringup.launch.py` has ~100 arguments. Typing ten of them correctly, at the
pool, under time pressure, is how a run gets lost -- and `ros2 launch` makes it
worse, because a mistyped `name:=value` is ignored without a word.

So the same arguments can live in a YAML file on the vehicle:

    # ~/.mongla/bringup.yaml
    vision: true
    flow: true
    pool_depth_m: 1.2
    fwd_model: gate_sharks

and `ros2 launch mongla_manager bringup.launch.py` reads it. Which value wins,
highest first:

    1. `name:=value` typed on the command line      (always wins)
    2. the file                                      (the deck's settings)
    3. the default written in bringup.launch.py      (the repository's)

The file is `$MONGLA_BRINGUP` if set, else `~/.mongla/bringup.yaml`; if
neither exists nothing changes. `MONGLA_BRINGUP=none` ignores the file.

Unlike the command line, the file is STRICT: a key that is not a bringup
argument stops the launch with the closest real name, and a value outside an
argument's choices stops it too. A typo here fails at launch, on the bench, and
not silently at depth.

An example with every argument and its default:
`src/mongla_manager/config/bringup.example.yaml` (generated by
`tools/gen_reference.py`).
"""
from __future__ import annotations

import difflib
import os
from pathlib import Path

ENV = 'MONGLA_BRINGUP'
DEFAULT_PATH = Path.home() / '.mongla' / 'bringup.yaml'


def config_path() -> Path | None:
    """The file bringup will read, or None if there is none to read."""
    env = os.environ.get(ENV, '').strip()
    if env.lower() in ('none', 'off', '0'):
        return None
    p = Path(env).expanduser() if env else DEFAULT_PATH
    if env and not p.exists():
        # Pointing at a file that is not there is a mistake worth stopping for:
        # the operator believes settings are applied that are not.
        raise RuntimeError(f'{ENV}={env}: no such file')
    return p if p.exists() else None


def _as_launch_string(value) -> str:
    """YAML value -> the string `name:=value` would have produced."""
    if isinstance(value, bool):
        return 'true' if value else 'false'
    if value is None:
        return ''
    if isinstance(value, (list, tuple)):
        return ','.join(str(v) for v in value)
    return str(value)


def read(path: Path, declared: set[str]) -> dict[str, str]:
    """{argument: value} from the file; refuses a key bringup does not declare."""
    import yaml
    body = yaml.safe_load(path.read_text()) or {}
    if not isinstance(body, dict):
        raise RuntimeError(f'{path}: expected `name: value` lines, got {type(body).__name__}')
    unknown = sorted(set(body) - declared)
    if unknown:
        hints = []
        for k in unknown:
            close = difflib.get_close_matches(str(k), declared, n=1)
            hints.append(f'{k!r}' + (f' (did you mean {close[0]!r}?)' if close else ''))
        raise RuntimeError(f'{path}: not a bringup argument: {", ".join(hints)}')
    return {str(k): _as_launch_string(v) for k, v in body.items()}


def apply(args: list) -> tuple[list, dict[str, str], Path | None]:
    """Re-default `DeclareLaunchArgument`s from the file.

    Returns (new argument list, the values the file set, the file's path).
    Arguments the file does not name are returned untouched.
    """
    from launch.actions import DeclareLaunchArgument
    path = config_path()
    if path is None:
        return args, {}, None
    declared = {a.name for a in args if isinstance(a, DeclareLaunchArgument)}
    values = read(path, declared)
    out = []
    for a in args:
        if not (isinstance(a, DeclareLaunchArgument) and a.name in values):
            out.append(a)
            continue
        desc = a.description.split(' Valid choices are:')[0]
        # Re-declaring with the file's value as the default puts it BELOW the
        # command line: launch only uses a default when `name:=` is not given.
        # The constructor checks the value against `choices` and raises.
        try:
            out.append(DeclareLaunchArgument(a.name, default_value=values[a.name],
                                             description=desc, choices=a.choices))
        except RuntimeError:
            raise RuntimeError(f'{path}: {a.name}: {values[a.name]!r} is not one '
                               f'of {a.choices}') from None
    return out, values, path
