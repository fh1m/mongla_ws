#!/usr/bin/env python3
"""Write tools/README.md: every tool, by folder, with the first sentence of its own description.

    python3 tools/ci/gen_tools_index.py           write the index
    python3 tools/ci/gen_tools_index.py --check   exit 1 if it is stale

The description is the tool's docstring (Python) or its opening comment
(shell), so the index is never a second copy to keep by hand: change what a
tool does, change its docstring, regenerate. A tool with no description is
refused, because a tool nobody can find out about is a black box.
"""
from __future__ import annotations

import ast
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
TOOLS = ROOT / 'tools'
OUT = TOOLS / 'README.md'
SKIP = {'README.md', '__pycache__'}

# The placement rule. A tool lives in the folder named for who reaches for it
# and when, so on a pool day the operator opens one folder, not a list of 150.
# The top level holds only the libraries the tools share. Anything else at the
# top level, or a sixth folder, is refused: decide where it goes, then add it.
FOLDERS = {
    'pool': 'the operator, on a pool or competition day: consoles, recorders, '
            'calibration and field checks',
    'bench': 'an engineer at the bench, with the board or the Pi: hardware '
             'probes, latency and timing benches, model compile and export',
    'ci': 'the checks and generators CI runs, and the audits behind them',
    'site': 'the figures and pages of the project site',
    'studies': 'one-off measurements over recorded footage or bags; each one '
               'answers a question in measured-bars.md',
}
LIBRARIES = {
    '_record_lib.sh', '_site_splice.py', '_where.py', 'archive_root.py',
    'code_text.py', 'data_root.py', 'launch_ast.py', 'launch_render.py',
}

HEADER = """# tools

Off the mission path: benches, audits, calibration aids, generators and the
operator console. Nothing on the vehicle imports these, and a tool here is
not a capability (`CLAUDE.md` §9). Each line is the tool's own description,
first sentence only.

**Where a tool goes.** By who reaches for it, and when. The top level holds
only the libraries the tools share; a new tool goes in one of the five
folders below, and `test/test_every_tool_is_indexed.py` refuses anything
else.

Generated by `python3 tools/ci/gen_tools_index.py`; the same test fails when
this page is stale.
"""


def _first_sentence(text: str) -> str:
    # To the first full stop, so a title like "Live:" carries the line after
    # it; a description with no full stop in 200 characters is cut there.
    text = ' '.join(text.split())
    m = re.match(r'(.+?\.)(\s|$)', text)
    out = m.group(1) if m else text
    if len(out) > 200:
        out = out[:200].rsplit(' ', 1)[0] + ' ...'
    return out.replace('|', '\\|')


def _python(path: pathlib.Path) -> str | None:
    try:
        return ast.get_docstring(ast.parse(path.read_text(encoding='utf-8')))
    except SyntaxError:
        return None


def _comment(path: pathlib.Path) -> str | None:
    lines = []
    for line in path.read_text(encoding='utf-8').splitlines()[:12]:
        s = line.strip()
        if s.startswith('#!'):
            continue
        for mark in ('#', '//', '/*', '*', '<!--'):
            if s.startswith(mark):
                s = s[len(mark):].strip(' */-!>')
                break
        else:
            if lines:
                break
            continue
        if s:
            lines.append(s)
        elif lines:
            break
    return ' '.join(lines) or None


def describe(path: pathlib.Path) -> str | None:
    """The tool's own description, or None if it has none."""
    if path.is_dir():
        main = path / f'{path.name}.py'
        candidates = [main] + sorted(p for p in path.iterdir() if p.is_file())
        for c in candidates:
            if c.is_file() and not c.name.startswith('.'):
                d = describe(c)
                if d:
                    return d
        return None
    if path.suffix == '.py':
        return _python(path)
    return _comment(path)


def misplaced() -> list[str]:
    """Top-level entries the placement rule does not allow."""
    return [p.name for p in sorted(TOOLS.iterdir())
            if p.name not in SKIP and not p.name.startswith('.')
            and p.name not in LIBRARIES
            and not (p.is_dir() and p.name in FOLDERS)]


def entries(folder: pathlib.Path) -> list[tuple[str, str | None]]:
    out = []
    for p in sorted(folder.iterdir(), key=lambda p: p.name.lower()):
        if p.name in SKIP or p.name.startswith('.'):
            continue
        if folder == TOOLS and p.name not in LIBRARIES:
            continue
        name = p.name + ('/' if p.is_dir() else '')
        d = describe(p)
        out.append((name, _first_sentence(d) if d else None))
    return out


def _table(rows: list[tuple[str, str | None]]) -> str:
    return ('| tool | what it does |\n|---|---|\n'
            + ''.join(f'| `{n}` | {d} |\n' for n, d in rows))


def render() -> str:
    bad = misplaced()
    if bad:
        raise SystemExit('not a shared library and not in one of '
                         f'{", ".join(FOLDERS)}: ' + ', '.join(bad))
    sections = [(f'tools/{f}/', why, entries(TOOLS / f)) for f, why in FOLDERS.items()]
    sections.append(('Shared libraries', 'the tools above, which import them; '
                     'nothing here is run on its own', entries(TOOLS)))
    missing = [n for _, _, rows in sections for n, d in rows if not d]
    if missing:
        raise SystemExit('no description (docstring or opening comment): '
                         + ', '.join(missing))
    body = ''.join(f'\n## {title}\n\nFor {why}.\n\n{_table(rows)}'
                   for title, why, rows in sections)
    return HEADER + body


def main(argv: list[str]) -> int:
    text = render()
    if '--check' in argv:
        if not OUT.exists() or OUT.read_text(encoding='utf-8') != text:
            print('tools/README.md is stale: run python3 tools/ci/gen_tools_index.py')
            return 1
        print('ok')
        return 0
    OUT.write_text(text, encoding='utf-8')
    n = sum(len(entries(TOOLS / f)) for f in FOLDERS)
    print(f'wrote {OUT.relative_to(ROOT)} ({n} tools)')
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
