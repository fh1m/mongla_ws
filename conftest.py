"""Make `import mongla_*` resolve to THIS checkout. Always. Everywhere.

THE PROBLEM THIS EXISTS TO KILL, because it has now cost several rounds.

Sourcing a colcon workspace puts its `install/` tree on `PYTHONPATH`:

    PYTHONPATH=/…/mongla_ws/install/mongla_vision/lib/python3.10/site-packages
               /…/mongla_ws/install/mongla_manager/lib/python3.10/site-packages
               …

`import mongla_vision` then resolves THERE, not to the source beside the test.
Three ways that bites, all of them silent:

  * IN A WORKTREE -- a second checkout (a branch under review, this one) has
    its own `src/` and NO install tree, so every test imports the OTHER
    workspace's build. Round 34 spent a session on a "drift bug" that was this:
    a test read 0.4 from an installed copy while the source beside it said
    0.20. Tonight it happened again -- a method added to `flow_math` was
    reported ABSENT by pytest while `grep` found it in the file.
  * ON THE PI -- `colcon build --symlink-install` COPIES rather than symlinks
    for this layout, so the install tree goes stale the moment source is
    edited, and the vehicle's suite validates code the vehicle is not running.
  * ANYWHERE -- a package deleted from source but still installed keeps
    passing its own tests.

The failure is always the same shape: the suite is green, and it is green
about the wrong file.

WHAT THIS DOES. `conftest.py` at the repo root is loaded by pytest before it
imports any test module, so it is early enough to fix `sys.path` for the whole
session. It puts every `src/<pkg>/` on the FRONT of the path and removes the
colcon `install/`+`build/` entries that would shadow them.

`mongla_interfaces` IS DELIBERATELY EXEMPT. Its Python is GENERATED by the
message compiler and exists only in the install tree -- there is no
`src/mongla_interfaces/mongla_interfaces/`. Purging its path would break
`from mongla_interfaces.msg import MonglaState` everywhere, so the rule is
"shadow only what we have source for", derived at run time rather than from a
hardcoded list that would rot the next time a package is added.
"""
import pathlib
import sys

_ROOT = pathlib.Path(__file__).resolve().parent
_SRC = _ROOT / 'src'


def _source_packages():
    """`src/<name>/<name>/` -- a real Python package, not a msg-only one."""
    if not _SRC.is_dir():
        return {}
    return {d.name: d for d in sorted(_SRC.iterdir())
            if d.is_dir() and (d / d.name).is_dir()}


def _install_shadow(entry: str, names) -> bool:
    """A colcon artefact for a package we have source for."""
    if '/install/' not in entry and '/build/' not in entry:
        return False
    return any(f'/{n}/' in entry for n in names)


def _pin_to_source():
    pkgs = _source_packages()
    if not pkgs:
        return []
    names = set(pkgs)

    # 1. Evict the shadows. Only ours, only where source exists.
    sys.path[:] = [p for p in sys.path if not _install_shadow(str(p), names)]

    # 2. Prepend our source dirs.
    for path in pkgs.values():
        entry = str(path)
        if entry in sys.path:
            sys.path.remove(entry)
        sys.path.insert(0, entry)

    # 3. Anything already imported from a shadow is still bound in
    #    sys.modules and would defeat both steps above. Drop those bindings so
    #    the next import re-resolves; harmless when nothing was imported yet.
    for mod in [m for m in list(sys.modules)
                if m.split('.')[0] in names]:
        installed = getattr(sys.modules[mod], '__file__', '') or ''
        if _install_shadow(installed, names):
            del sys.modules[mod]

    return list(pkgs)


PINNED = _pin_to_source()


# --------------------------------------------------------------------------- #
#  The published test counts come from the last FULL run, never by hand.      #
# --------------------------------------------------------------------------- #
# A run that covered every suite, with no -k / -m / -x / --lf / --deselect and
# nothing left unreported, writes docs/stats.json and copies it into the README
# and the site (tools/ci/published_counts.py). Anything less leaves them alone, so a
# quick run of one file never publishes a smaller number.
# Every launch leaves a file behind (BUGS B-142). launch_ros writes the
# parameters of each Node given a dict to NamedTemporaryFile(delete=False), and
# nothing removes it: 784,505 `launch_params_*` filled the dev box's 7.8 GB /tmp
# (a RAM disk) by 2026-11-20. So the session gets its own TMPDIR, which every
# launch subprocess inherits, and it is removed when the session ends. pytest's
# own temp root is pinned first (PYTEST_DEBUG_TEMPROOT, which it reads before
# TMPDIR), so tmp_path keeps its usual place and its retention.
import os as _os          # noqa: E402
import shutil as _shutil  # noqa: E402
import tempfile as _tempfile  # noqa: E402

_os.environ.setdefault('PYTEST_DEBUG_TEMPROOT', _tempfile.gettempdir())
SESSION_TMP = _tempfile.mkdtemp(prefix='mongla-test-session-',
                                dir=_os.environ['PYTEST_DEBUG_TEMPROOT'])
_os.environ['TMPDIR'] = SESSION_TMP
_tempfile.tempdir = None        # gettempdir() caches; read TMPDIR again


def pytest_unconfigure(config):
    _shutil.rmtree(SESSION_TMP, ignore_errors=True)


_OUTCOMES = {}          # nodeid -> outcome ('passed', 'failed', 'skipped', ...)


def pytest_runtest_logreport(report):
    """One outcome per test, in the words pytest's own summary uses."""
    xfail = hasattr(report, 'wasxfail')
    if report.failed:
        outcome = 'failed' if report.when == 'call' else 'error'
    elif report.skipped:
        outcome = 'xfailed' if xfail else 'skipped'
    elif report.when == 'call':
        outcome = 'xpassed' if xfail else 'passed'
    else:
        return                      # a passing setup/teardown says nothing new
    if _OUTCOMES.get(report.nodeid) != 'error':     # an error is final
        _OUTCOMES[report.nodeid] = outcome


def _full_run(session) -> bool:
    opt = session.config.option
    narrowed = (opt.keyword or opt.markexpr or opt.maxfail or getattr(opt, 'lf', False)
                or getattr(opt, 'deselect', None) or getattr(opt, 'failedfirst', False))
    return (not narrowed and session.testscollected > 0
            and len(_OUTCOMES) == session.testscollected)


def pytest_sessionfinish(session, exitstatus):
    if not _full_run(session):
        return
    sys.path.insert(0, str(_ROOT / 'tools'))  # shared libraries
    sys.path.insert(0, str(_ROOT / 'tools' / 'ci'))
    import published_counts
    counts = {}
    for nodeid, outcome in _OUTCOMES.items():
        suite = published_counts.suite_of(nodeid.split('::')[0])
        if suite is None:
            continue
        c = counts.setdefault(suite, {})
        c[outcome] = c.get(outcome, 0) + 1
    if set(counts) != set(published_counts.SUITE_NAMES):
        return                      # not every suite ran: not a full run
    published_counts.record(counts, session.testscollected)


# --------------------------------------------------------------------------- #
#  A fixture whose setup fails must not take every later ROS test with it.    #
# --------------------------------------------------------------------------- #
# The suites run in one process (tools/ci/ci_ros.sh), and a fixture that calls
# `rclpy.init()` and then fails an assert never reaches its `rclpy.shutdown()`.
# Every later `rclpy.init()` then raises "Context.init() must only be called
# once", so one discovery timeout on the Jazzy runner read as dozens of
# failures across three packages, hiding which one was real. Only a context
# this test's own setup created is shut down; a module-scoped one that was
# already up is left alone.
import pytest  # noqa: E402


def _rclpy_up() -> bool:
    rclpy = sys.modules.get('rclpy')
    try:
        return bool(rclpy is not None and rclpy.ok())
    except Exception:                                    # noqa: BLE001
        return False


@pytest.hookimpl(hookwrapper=True)
def pytest_runtest_setup(item):
    before = _rclpy_up()
    outcome = yield
    if outcome.excinfo is not None and not before and _rclpy_up():
        try:
            sys.modules['rclpy'].shutdown()
        except Exception:                                # noqa: BLE001
            pass
